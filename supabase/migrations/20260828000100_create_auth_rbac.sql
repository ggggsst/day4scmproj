alter table core.app_user enable row level security;
alter table core.audit_log enable row level security;

revoke all on table core.app_user from anon;
revoke all on table core.audit_log from anon;
grant select on table core.app_user, core.audit_log to authenticated;
grant update (role, active) on table core.app_user to authenticated;
grant usage, select on sequence core.audit_log_id_seq to authenticated;
revoke execute on function core.admin_change_user_role(uuid, text) from public;
revoke execute on function core.admin_change_user_active(uuid, boolean) from public;
grant execute on function core.admin_change_user_role(uuid, text) to authenticated;
grant execute on function core.admin_change_user_active(uuid, boolean) to authenticated;

drop policy if exists app_user_select on core.app_user;
create policy app_user_select on core.app_user
for select to authenticated
using (user_id = auth.uid() or core.is_admin());

drop policy if exists app_user_update on core.app_user;
create policy app_user_update on core.app_user
for update to authenticated
using (core.is_admin())
with check (core.is_admin());

drop policy if exists audit_log_select on core.audit_log;
create policy audit_log_select on core.audit_log
for select to authenticated
using (actor = auth.uid() or core.is_admin());

drop policy if exists audit_log_insert on core.audit_log;
create policy audit_log_insert on core.audit_log
for insert to authenticated
with check (core.is_admin() and actor = auth.uid());
